#!/usr/bin/env python3
"""Render one `.qp/INDEX.md` candidate from owner record frontmatter."""
from __future__ import annotations

import argparse
import json
import os
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

INDEX_NOTICE = "<!-- Generated by Akosile. Edit records, not this file. -->"
OWNER_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
RECORD_ID_RE = re.compile(r"^\d{8}-(?P<slug>[a-z0-9]+(?:-[a-z0-9]+)*)$")


class IndexError(Exception):
    def __init__(self, code: str, message: str, **details: Any) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details

    def payload(self) -> dict[str, Any]:
        result: dict[str, Any] = {"code": self.code, "message": self.message}
        if self.details:
            result["details"] = self.details
        return result


class FrontmatterLoader(yaml.SafeLoader):
    pass


FrontmatterLoader.yaml_implicit_resolvers = {
    key: [(tag, pattern) for tag, pattern in rules if tag != "tag:yaml.org,2002:timestamp"]
    for key, rules in yaml.SafeLoader.yaml_implicit_resolvers.items()
}


def unique_mapping(
    loader: FrontmatterLoader, node: yaml.nodes.MappingNode, deep: bool = False
) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if not isinstance(key, str) or key in result:
            raise yaml.constructor.ConstructorError(
                "while constructing frontmatter",
                node.start_mark,
                "frontmatter keys must be unique strings",
                key_node.start_mark,
            )
        result[key] = loader.construct_object(value_node, deep=deep)
    return result


FrontmatterLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def frontmatter(text: str) -> dict[str, Any]:
    if not text.startswith("---\n"):
        raise IndexError("INVALID_FRONTMATTER", "Record must start with YAML frontmatter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise IndexError("INVALID_FRONTMATTER", "Record frontmatter is not terminated")
    try:
        metadata = yaml.load(text[4:end], Loader=FrontmatterLoader) or {}
    except yaml.YAMLError as error:
        raise IndexError(
            "INVALID_FRONTMATTER", "Record frontmatter is not valid YAML", error=str(error)
        ) from error
    if not isinstance(metadata, dict):
        raise IndexError("INVALID_FRONTMATTER", "Record frontmatter must be a mapping")
    return metadata


def required_string(metadata: dict[str, Any], key: str) -> str:
    value = metadata.get(key)
    if not isinstance(value, str) or not value.strip():
        raise IndexError("INVALID_RECORD", f"{key} must be a non-empty string", field=key)
    return value


def instant(value: Any) -> datetime:
    if not isinstance(value, str):
        raise IndexError("INVALID_UPDATED_AT", "updated_at must be offset-aware ISO-8601")
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as error:
        raise IndexError("INVALID_UPDATED_AT", "updated_at must be offset-aware ISO-8601") from error
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise IndexError("INVALID_UPDATED_AT", "updated_at must include a UTC offset")
    return parsed.astimezone(timezone.utc)


def reject_symlinks(workspace: Path, path: Path) -> None:
    current = workspace
    for part in path.relative_to(workspace).parts:
        current /= part
        if current.is_symlink():
            raise IndexError("SYMLINK_PATH", "Record path cannot traverse symbolic links")


def inspect_record(workspace: Path, path: Path) -> dict[str, Any]:
    reject_symlinks(workspace, path)
    metadata = frontmatter(path.read_text(encoding="utf-8"))
    owner = required_string(metadata, "owner")
    if not OWNER_RE.fullmatch(owner):
        raise IndexError("INVALID_OWNER", "owner must be a canonical ASCII skill name")
    if owner != path.parent.parent.name:
        raise IndexError("OWNER_PATH_MISMATCH", "owner does not match its directory")

    match = RECORD_ID_RE.fullmatch(path.parent.name)
    if not match:
        raise IndexError("INVALID_RECORD_ID", "record directory must be <YYYYMMDD>-<stable-slug>")

    revision = metadata.get("revision")
    if isinstance(revision, bool) or not isinstance(revision, int) or revision < 1:
        raise IndexError("INVALID_RECORD", "revision must be a positive integer", field="revision")

    slug = match.group("slug")
    view = path.parent / f"{slug}.html"
    legacy = path.parent / "index.html"
    return {
        "updated_at": required_string(metadata, "updated_at"),
        "instant": instant(metadata.get("updated_at")),
        "owner": owner,
        "record_type": required_string(metadata, "record_type"),
        "title": required_string(metadata, "title"),
        "status": required_string(metadata, "status"),
        "record": path.relative_to(workspace).as_posix(),
        "view": view.relative_to(workspace).as_posix() if view.is_file() and not view.is_symlink() else None,
        "legacy": legacy.relative_to(workspace).as_posix() if legacy.is_file() and not legacy.is_symlink() else None,
        "expected_view": view.relative_to(workspace).as_posix(),
    }


def cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(rows: list[dict[str, Any]], invalid: list[dict[str, str]], legacy: list[dict[str, str]]) -> str:
    lines = [
        INDEX_NOTICE,
        "",
        "# QP workspace records",
        "",
        "| Updated | Owner | Type | Title | Status | Record | View |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in sorted(rows, key=lambda item: item["instant"], reverse=True):
        view = f"[HTML]({row['view']})" if row["view"] else "—"
        lines.append(
            f"| {cell(row['updated_at'])} | `{cell(row['owner'])}` | {cell(row['record_type'])} | "
            f"{cell(row['title'])} | {cell(row['status'])} | [Record]({row['record']}) | {view} |"
        )
    if not rows:
        lines.append("| — | — | — | — | — | — | — |")
    if invalid:
        lines += ["", "## Invalid records", ""]
        lines += [f"- `{item['path']}` — `{item['code']}`: {item['message']}" for item in invalid]
    if legacy:
        lines += ["", "## Legacy HTML entrypoints", ""]
        lines += [
            f"- `{item['path']}` — use `{item['expected']}` for the next owner-authorized projection"
            for item in legacy
        ]
    return "\n".join(lines) + "\n"


def build(workspace: Path, output: Path) -> dict[str, Any]:
    supplied = Path(os.path.abspath(workspace.expanduser()))
    if supplied.is_symlink():
        raise IndexError("SYMLINK_WORKSPACE", "workspace cannot be a symbolic link")
    if not supplied.is_dir():
        raise IndexError("WORKSPACE_MISSING", "workspace must be an existing directory")
    workspace = supplied.resolve()
    records = workspace / "records"
    if records.is_symlink():
        raise IndexError("SYMLINK_RECORDS", "records cannot be a symbolic link")

    rows: list[dict[str, Any]] = []
    invalid: list[dict[str, str]] = []
    legacy: list[dict[str, str]] = []
    for path in sorted(records.glob("*/*/record.md")) if records.exists() else ():
        try:
            row = inspect_record(workspace, path)
            rows.append(row)
            if row["legacy"]:
                legacy.append({"path": row["legacy"], "expected": row["expected_view"]})
        except (IndexError, UnicodeError, OSError) as error:
            if isinstance(error, IndexError):
                code, message = error.code, error.message
            else:
                code, message = "READ_FAILED", str(error)
            invalid.append({"path": path.relative_to(workspace).as_posix(), "code": code, "message": message})

    output = Path(os.path.abspath(output.expanduser()))
    try:
        output.relative_to(workspace)
    except ValueError:
        pass
    else:
        raise IndexError(
            "OUTPUT_INSIDE_WORKSPACE",
            "output must be a separate candidate outside the authoritative workspace",
        )
    if output.is_symlink():
        raise IndexError("SYMLINK_OUTPUT", "output cannot be a symbolic link")
    if not output.parent.is_dir():
        raise IndexError("OUTPUT_PARENT_MISSING", "output parent must already exist")
    output.write_text(render(rows, invalid, legacy), encoding="utf-8", newline="\n")
    return {
        "workspace": str(workspace),
        "output": str(output),
        "records": len(rows),
        "invalid": invalid,
        "legacy_html": legacy,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        result = build(args.workspace, args.output)
    except IndexError as error:
        print(json.dumps({"ok": False, "error": error.payload()}, ensure_ascii=False, indent=2))
        raise SystemExit(2) from error
    print(json.dumps({"ok": True, "result": result}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
